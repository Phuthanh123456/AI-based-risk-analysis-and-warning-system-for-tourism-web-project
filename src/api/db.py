class _HybridRow(dict):
    """Dictionary-style database row that also supports SQLite-like indexes."""

    def __getitem__(self, key):
        if isinstance(key, int):
            key = tuple(self.keys())[key]
        return super().__getitem__(key)


def _hybrid_row(cursor):
    # psycopg invokes row_factory for commands such as CREATE TABLE too;
    # those statements have no result description and never produce rows.
    if cursor.description is None:
        return tuple

    names = [column.name for column in cursor.description]

    def make_row(values):
        return _HybridRow(zip(names, values))

    return make_row


class _PostgresConnection:
    """Small compatibility layer for existing sqlite-style `?` queries."""

    def __init__(self, connection):
        self._connection = connection

    def execute(self, sql, params=()):
        sql = sql.replace(" IS NOT ", " IS DISTINCT FROM ")
        return self._connection.execute(sql.replace("?", "%s"), params)

    def commit(self):
        return self._connection.commit()

    def close(self):
        return self._connection.close()

    def __enter__(self):
        self._connection.__enter__()
        return self

    def __exit__(self, exc_type, exc, tb):
        return self._connection.__exit__(exc_type, exc, tb)


def _is_postgres() -> bool:
    return bool(DATABASE_URL)


def get_conn():
    if _is_postgres():
        import psycopg

        connection = psycopg.connect(DATABASE_URL, row_factory=_hybrid_row, connect_timeout=10)
        return _PostgresConnection(connection)

    os.makedirs(os.path.dirname(DB_PATH), exist_ok=True)
    conn = sqlite3.connect(DB_PATH, check_same_thread=False)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def init_db() -> None:
    conn = get_conn()
    try:
        if _is_postgres():
            for statement in _POSTGRES_STATEMENTS:
                conn.execute(statement)
        else:
            conn.executescript(_SQLITE_SCHEMA)
            columns = {row["name"] for row in conn.execute("PRAGMA table_info(push_subscriptions)")}
            if "last_alert_at" not in columns:
                conn.execute("ALTER TABLE push_subscriptions ADD COLUMN last_alert_at TEXT")
        conn.commit()
    finally:
        conn.close()


